import Foundation
import CoreGraphics
import CryptoKit
import ImageIO
import UniformTypeIdentifiers

let width = 80, height = 48
let colors: [[UInt8]] = [
    [220, 40, 40, 255], [20, 180, 70, 255],
    [25, 70, 220, 255], [230, 190, 20, 255],
]
var pixels = [UInt8](repeating: 0, count: width * height * 4)
for y in 0..<height {
    for x in 0..<width {
        let color = colors[(y >= height / 2 ? 2 : 0) + (x >= width / 2 ? 1 : 0)]
        for channel in 0..<4 {
            pixels[(y * width + x) * 4 + channel] = color[channel]
        }
    }
}
let provider = CGDataProvider(data: Data(pixels) as CFData)!
let image = CGImage(
    width: width, height: height, bitsPerComponent: 8, bitsPerPixel: 32,
    bytesPerRow: width * 4, space: CGColorSpaceCreateDeviceRGB(),
    bitmapInfo: CGBitmapInfo(rawValue: CGImageAlphaInfo.premultipliedLast.rawValue)
        .union(.byteOrder32Big),
    provider: provider, decode: nil, shouldInterpolate: false, intent: .defaultIntent
)!
let encoded = NSMutableData()
let destination = CGImageDestinationCreateWithData(
    encoded, UTType.heic.identifier as CFString, 1, nil
)!
CGImageDestinationAddImage(destination, image, [
    kCGImageDestinationLossyCompressionQuality: 0.85,
    kCGImagePropertyOrientation: 6,
    kCGImagePropertyGPSDictionary: [
        kCGImagePropertyGPSLatitude: 0.0, kCGImagePropertyGPSLongitude: 0.0,
        kCGImagePropertyGPSLatitudeRef: "N", kCGImagePropertyGPSLongitudeRef: "E",
    ],
    kCGImagePropertyExifDictionary: [
        kCGImagePropertyExifDateTimeOriginal: "2000:01:01 00:00:00",
    ],
] as CFDictionary)
guard CGImageDestinationFinalize(destination) else {
    fatalError("Synthetic HEIC encoding unavailable; existing fixture unchanged")
}
let data = encoded as Data
precondition(data.count < 128 * 1024, "Manufactured fixture exceeds its bound")
let bytes = [UInt8](data)

func configuration(_ start: Int, _ end: Int, _ depth: Int = 0) -> [UInt8]? {
    precondition(depth <= 8)
    var offset = start
    while offset < end {
        precondition(offset + 8 <= end)
        let size = bytes[offset..<offset + 4].reduce(0) { ($0 << 8) | Int($1) }
        precondition(size >= 8 && size <= end - offset)
        let type = String(bytes: bytes[offset + 4..<offset + 8], encoding: .ascii)!
        if type == "hvcC" { return Array(bytes[offset + 8..<offset + size]) }
        if ["meta", "iprp", "ipco"].contains(type) {
            let child = offset + (type == "meta" ? 12 : 8)
            precondition(child <= offset + size)
            if let result = configuration(child, offset + size, depth + 1) {
                return result
            }
        }
        offset += size
    }
    return nil
}
guard let codec = configuration(0, bytes.count), codec.count >= 23 else {
    fatalError("The manufactured HEIC has no bounded codec declaration")
}
precondition(codec[0] == 1 && codec[1] & 31 == 3, "Expected HEVC Main Still Picture")
precondition(codec[16] & 3 == 1, "Expected actual YUV420, not a substituted subtype")
precondition(codec[17] & 7 == 0 && codec[18] & 7 == 0, "Expected 8-bit components")

let source = CGImageSourceCreateWithData(data as CFData, nil)!
let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil)! as NSDictionary
precondition((properties[kCGImagePropertyOrientation] as? NSNumber)?.intValue == 6)
precondition((properties[kCGImagePropertyPixelWidth] as? NSNumber)?.intValue == width)
precondition((properties[kCGImagePropertyPixelHeight] as? NSNumber)?.intValue == height)
let gps = properties[kCGImagePropertyGPSDictionary] as! NSDictionary
precondition((gps[kCGImagePropertyGPSLatitude] as? NSNumber)?.doubleValue == 0)
precondition((gps[kCGImagePropertyGPSLongitude] as? NSNumber)?.doubleValue == 0)
let exif = properties[kCGImagePropertyExifDictionary] as! NSDictionary
precondition(exif[kCGImagePropertyExifDateTimeOriginal] as? String == "2000:01:01 00:00:00")
let digest = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()

let output = """
// Generated by tool/generate_heic420_fixture.swift from fictional color quadrants.
// Source 80x48 RGBA, orientation6, ImageIO quality0.85.
// Verified hvcC: Main Still Picture(profile3), YUV420(chroma1), 8-bit luma/chroma.
// Fictional metadata: GPS0,0; original date2000:01:01 00:00:00.
// Raw corners: red(220,40,40), green(20,180,70), blue(25,70,220), yellow(230,190,20).
// Upright48x80 corners: blue, red, yellow, green; native tolerance35/channel.
// SHA256: \(digest)
import 'dart:convert';
import 'dart:typed_data';

Uint8List generatedRotatedHeic420() => base64Decode(
  '\(data.base64EncodedString())',
);

"""
let repository = URL(fileURLWithPath: #filePath).standardizedFileURL
    .deletingLastPathComponent().deletingLastPathComponent()
let target = repository.appendingPathComponent(
    "integration_test/support/generated_rotated_heic420.dart"
)
try output.write(to: target, atomically: true, encoding: .utf8)
print("Manufactured HEIC420: bytes=\(data.count) profile=3 chroma=1 depth=8 orientation=6 GPS=fictional sha256=\(digest)")
