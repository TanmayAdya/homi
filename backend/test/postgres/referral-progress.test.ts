import assert from 'node:assert/strict';
import { createHash, randomUUID } from 'node:crypto';
import { after, before, test } from 'node:test';
import { TestPostgres } from './harness.ts';
import { OWNER, OTHER, create } from './fixtures.ts';
import { applyMigrations } from '../../src/storage/migrate.ts';
import { PostgresCaseRepository } from '../../src/storage/postgres-case-repository.ts';
import { captureDatabaseBackup, restoreDatabaseBackup } from '../../src/storage/database-backup.ts';
import { canonicalJson } from '../../src/evidence/validation.ts';
import type { NextStepTask, ProgressSave } from '../../src/tracking/progress.ts';
let cluster: TestPostgres, target: TestPostgres;
before(async () => { cluster = await TestPostgres.start(); await applyMigrations(cluster.pool()); });
after(async () => { await target?.close(); await cluster?.close(); });
test('referral imports obey forced RLS, concurrent receipts and private backup/restore', async () => {
  const admin = cluster.pool();
  await admin.query('CREATE ROLE referral_runtime LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS IN ROLE safeathome_app');
  const runtime = cluster.pool('referral_runtime'), repo = new PostgresCaseRepository(runtime), { caseId } = await create(repo);
  const at = '2026-10-24T12:00:00.000Z';
  const original = { id:'local-one', providerId:'referral-211-national', title:'Fictional repair referral', responsible:'Fictional resident', dueDate:'2026-01-01', findingId:null, createdAt:at, completedAt:at };
  const task: NextStepTask = { id:'import-one', programId:null, findingId:null, formId:null, title:original.title, kind:'follow_up', state:'completed', responsiblePerson:original.responsible, dueOn:null, basedOnCaseRevision:1, basedOnRuleVersion:null, revision:1, sourceEventId:null,
    referral:{providerId:original.providerId,imported:{sourceTaskId:original.id,sourceHash:createHash('sha256').update(canonicalJson(original)).digest('hex'),original,contactNote:'Fictional private contact note'}} };
  const request = (id:string):ProgressSave => ({schemaVersion:'3',includeReferrals:true,caseId,expectedCaseRevision:1,expectedProgressRevision:0,mutationId:randomUUID(),operation:{type:'put_task',expectedTaskRevision:0,task:{...task,id}}});
  const a=request('import-one'), b=request('import-two');
  const results=await Promise.all([repo.saveProgressForUser(OWNER,a,at,[]),repo.saveProgressForUser(OWNER,b,at,[])]);
  assert.deepEqual(results.map(r=>r.status).sort(),['found','progress_conflict']);
  const winner=results.findIndex(r=>r.status==='found');
  assert.deepEqual(await repo.saveProgressForUser(OWNER,[a,b][winner],at,[]),results[winner]);
  const duplicate={...[a,b][1-winner],expectedProgressRevision:1};
  assert.equal((await repo.saveProgressForUser(OWNER,duplicate,at,[])).status,'task_conflict');
  assert.equal((await repo.readProgressForUser(OTHER,caseId)).status,'not_found');
  assert.equal((await runtime.query('SELECT progress FROM safeathome_private.cases')).rowCount,0);
  const expected=await repo.readProgressForUser(OWNER,caseId);
  const origin='https://fictional-referral.supabase.co', archive=await captureDatabaseBackup(admin,origin);
  target=await TestPostgres.start(); const targetAdmin=target.pool(); await applyMigrations(targetAdmin); await restoreDatabaseBackup(targetAdmin,archive,origin);
  await targetAdmin.query('CREATE ROLE referral_restore LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS IN ROLE safeathome_app');
  const restored=new PostgresCaseRepository(targetAdmin);
  assert.deepEqual(await restored.readProgressForUser(OWNER,caseId),expected);
  assert.equal((await repo.deleteCaseIfCurrent({userId:OWNER,caseId,revision:1,expectedCatalogRevision:0})).status,'deleted');
  assert.equal((await repo.readProgressForUser(OWNER,caseId)).status,'not_found');
});
